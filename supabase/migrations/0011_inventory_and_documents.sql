-- 0Gauge Recovery — inventory quantity ledger + invoice/outgoing-order
-- document types. Phase 1 of "scan-to-invoice": fuses barcode/photo
-- scanning into this app so a scan session can become a quote (unchanged,
-- existing flow), an invoice (new — printed, paid, tracked), a vendor
-- inventory receipt (new — no header document, just ledger rows), or an
-- outgoing order to another shop (new). See docs/INVENTORY_AND_SCANNING.md.
--
-- This is a real pivot from catalog_items' original "selling catalog, not
-- real-time inventory" framing (see docs/CATALOG_AND_PACKAGES.md) — the
-- user explicitly wants received/sold/transferred quantities tracked now.
-- quantity_on_hand defaults to 0 and is entirely additive/opt-in per item;
-- nothing about quoting requires it, same as before.

-- ---------------------------------------------------------------------------
-- catalog_items: quantity tracking + generated-code bookkeeping
-- ---------------------------------------------------------------------------

alter table public.catalog_items
  add column quantity_on_hand integer not null default 0,
  -- True when `upc` was generated by this app (GS1 in-store reserved range,
  -- see src/lib/upc.ts) rather than a real, looked-up manufacturer code.
  -- Drives both display ("Internal code" vs "UPC") and the label-print queue.
  add column upc_is_generated boolean not null default false,
  -- Null = still needs a label printed (only meaningful when upc_is_generated).
  add column label_printed_at timestamptz;

-- ---------------------------------------------------------------------------
-- invoices / invoice_items — a single finalized, itemized sale. Flat (no
-- tiers/options), unlike quotes, since by the time something is an invoice
-- staff have already decided what's being sold.
-- ---------------------------------------------------------------------------

create type invoice_status as enum ('draft', 'paid', 'void');

-- Broader than the existing `payment_method` enum (0004) on purpose — that
-- one is specifically for online deposit-payment links on a quote. An
-- invoice is usually paid in person, so this adds cash/card/other.
create type invoice_payment_method as enum ('cash', 'card', 'zelle', 'cashapp', 'venmo', 'paypal', 'link', 'other');

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops (id) on delete cascade,
  customer_id uuid references public.customers (id) on delete set null,
  -- Sequential per shop (1, 2, 3, ...), assigned by the trigger below — a
  -- human-friendly number to print/reference, distinct from the row's uuid.
  invoice_number integer not null,
  status invoice_status not null default 'draft',
  payment_method invoice_payment_method,
  payment_amount_cents bigint check (payment_amount_cents is null or payment_amount_cents >= 0),
  paid_at timestamptz,
  subtotal_cents bigint not null default 0 check (subtotal_cents >= 0),
  total_cents bigint not null default 0 check (total_cents >= 0),
  notes text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (shop_id, invoice_number)
);

create index invoices_shop_idx on public.invoices (shop_id, created_at desc);
create index invoices_shop_status_idx on public.invoices (shop_id, status);

create trigger invoices_updated_at before update on public.invoices
  for each row execute function public.set_updated_at();

-- Assigns invoice_number = next per shop. Uses an advisory xact lock keyed
-- on the shop so two concurrent inserts for the same shop don't race to the
-- same number (the lock releases automatically at transaction end).
create or replace function public.assign_invoice_number()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform pg_advisory_xact_lock(hashtext('invoice:' || new.shop_id::text));
  select coalesce(max(invoice_number), 0) + 1 into new.invoice_number
  from public.invoices where shop_id = new.shop_id;
  return new;
end;
$$;

create trigger invoices_assign_number before insert on public.invoices
  for each row execute function public.assign_invoice_number();

create table public.invoice_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.invoices (id) on delete cascade,
  -- Nullable: a custom line item (fee, misc part) has no catalog product
  -- behind it, same precedent as quote_items.category being nullable.
  catalog_item_id uuid references public.catalog_items (id) on delete set null,
  brand text,
  model text,
  name text not null,
  quantity integer not null default 1 check (quantity >= 1),
  unit_price_cents bigint not null default 0 check (unit_price_cents >= 0),
  category product_category,
  position integer not null default 0
);

create index invoice_items_invoice_idx on public.invoice_items (invoice_id);

-- ---------------------------------------------------------------------------
-- outgoing_orders / outgoing_order_items — stock sent to another shop.
-- Same shape as invoices minus payment; adds a destination name.
-- ---------------------------------------------------------------------------

create type outgoing_order_status as enum ('draft', 'sent');

