create index outgoing_order_items_order_idx on public.outgoing_order_items (outgoing_order_id);

-- ---------------------------------------------------------------------------
-- stock_movements — append-only ledger. quantity_on_hand is derived from
-- this (kept in sync by apply_stock_movement below), not hand-edited.
-- ---------------------------------------------------------------------------

create type stock_movement_type as enum ('receiving', 'outgoing_order', 'sale', 'adjustment');

create table public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops (id) on delete cascade,
  catalog_item_id uuid not null references public.catalog_items (id) on delete cascade,
  movement_type stock_movement_type not null,
  -- Signed: positive for receiving/adjustment-up, negative for sale/outgoing_order.
  quantity_delta integer not null check (quantity_delta <> 0),
  unit_cost_cents bigint check (unit_cost_cents is null or unit_cost_cents >= 0),
  -- Vendor name (receiving) or destination shop name (outgoing_order), free text.
  counterparty_name text,
  source_invoice_id uuid references public.invoices (id) on delete set null,
  source_outgoing_order_id uuid references public.outgoing_orders (id) on delete set null,
  note text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index stock_movements_shop_created_idx on public.stock_movements (shop_id, created_at desc);
create index stock_movements_item_idx on public.stock_movements (catalog_item_id, created_at desc);

-- ---------------------------------------------------------------------------
-- RLS — same shop-scoped pattern as catalog_items_all / package_templates_all.
-- ---------------------------------------------------------------------------

alter table public.invoices enable row level security;
alter table public.invoice_items enable row level security;
alter table public.outgoing_orders enable row level security;
alter table public.outgoing_order_items enable row level security;
alter table public.stock_movements enable row level security;

create policy invoices_all on public.invoices
  for all to authenticated
  using (public.is_shop_member(shop_id))
  with check (public.is_shop_member(shop_id));

create policy invoice_items_all on public.invoice_items
  for all to authenticated
  using (exists (select 1 from public.invoices i where i.id = invoice_id and public.is_shop_member(i.shop_id)))
  with check (exists (select 1 from public.invoices i where i.id = invoice_id and public.is_shop_member(i.shop_id)));

create policy outgoing_orders_all on public.outgoing_orders
  for all to authenticated
  using (public.is_shop_member(shop_id))
  with check (public.is_shop_member(shop_id));

create policy outgoing_order_items_all on public.outgoing_order_items
  for all to authenticated
  using (exists (select 1 from public.outgoing_orders o where o.id = outgoing_order_id and public.is_shop_member(o.shop_id)))
  with check (exists (select 1 from public.outgoing_orders o where o.id = outgoing_order_id and public.is_shop_member(o.shop_id)));

-- Read-only for shop members via RLS — every write goes through
-- apply_stock_movement() below so quantity_on_hand can never drift out of
-- sync with the ledger (no direct insert/update/delete policy on purpose).
create policy stock_movements_select on public.stock_movements
  for select to authenticated
  using (public.is_shop_member(shop_id));

-- ---------------------------------------------------------------------------
-- apply_stock_movement — the only way quantity_on_hand changes. Inserts the
-- ledger row and updates the item's quantity atomically (one function
-- invocation = one transaction), avoiding read-modify-write races when two
-- staff scan/receive/sell at the same time.
-- ---------------------------------------------------------------------------

create or replace function public.apply_stock_movement(
  p_catalog_item_id uuid,
  p_movement_type stock_movement_type,
  p_quantity_delta integer,
  p_unit_cost_cents bigint default null,
  p_counterparty_name text default null,
  p_source_invoice_id uuid default null,
  p_source_outgoing_order_id uuid default null,
  p_note text default null
)
returns public.stock_movements
language plpgsql
security definer
set search_path = public
as $$
declare
  v_shop_id uuid;
  v_movement public.stock_movements;
begin
  select shop_id into v_shop_id from public.catalog_items where id = p_catalog_item_id;
  if v_shop_id is null then
    raise exception 'Unknown catalog item';
  end if;
  if not public.is_shop_member(v_shop_id) then
    raise exception 'Not a member of this shop';
  end if;

  insert into public.stock_movements (
    shop_id, catalog_item_id, movement_type, quantity_delta, unit_cost_cents,
    counterparty_name, source_invoice_id, source_outgoing_order_id, note, created_by
  ) values (
    v_shop_id, p_catalog_item_id, p_movement_type, p_quantity_delta, p_unit_cost_cents,
    p_counterparty_name, p_source_invoice_id, p_source_outgoing_order_id, p_note, auth.uid()
  )
  returning * into v_movement;

  update public.catalog_items
  set quantity_on_hand = quantity_on_hand + p_quantity_delta
  where id = p_catalog_item_id;

  return v_movement;
end;
$$;

grant execute on function public.apply_stock_movement to authenticated;
