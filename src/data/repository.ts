  generateSku(brand: string | null, model: string): Promise<string>
  /** Stamps labelPrintedAt so a printed item drops out of the label queue. */
  markLabelPrinted(catalogItemId: string): Promise<void>

  /** Local catalog match by UPC/SKU only — lookupProductByUpc below wraps this with an external-lookup fallback. */
  findCatalogItemByCode(code: string): Promise<CatalogItem | null>
  /**
   * Local catalog first, then (production only) an external UPC database.
   * `options.fast` stops there instead of falling through to the AI/web
   * search — see ProductResolveRequest. `options.brandHint` scopes any
   * search that does run to the brand currently being received.
   */
  lookupProductByUpc(code: string, options?: { fast?: boolean; brandHint?: string | null }): Promise<UpcLookupResult>
  /** AI+web-search autocomplete for a partially-typed SKU/model/name when adding a new catalog product. `brandHint` scopes the search to the brand being received. Demo mode never makes a real call — always resolves []. Production degrades to [] on any failure rather than throwing, same pattern as lookupProductByUpc. Delegates to resolveProduct() underneath. */
  lookupProductSuggestions(query: string, brandHint?: string | null): Promise<ProductSuggestionResult>
  /** Ask the backend whether product lookup actually works right now, and why not if it doesn't. */
  testProductLookup(): Promise<ProductLookupSelfTest>
  /**
   * Products other shops have already identified.
   *
   * Checked before any web/AI call: a product one shop paid to resolve should
   * be free for the next, which is the entire point of the shared catalog.
   * Never throws — a shared-catalog outage must not block manual entry.
   */
  searchGlobalProducts(query: string): Promise<GlobalProductMatch[]>
  /**
   * The universal resolver: called when a barcode or typed query doesn't
   * match anything already in this shop's catalog. Never throws and never
   * dead-ends — an empty candidate list is a valid, safe result (caller
   * falls back to a custom/temporary item using retainedInput). Demo mode
   * never makes a real AI/web call — see DemoRepository for its
   * deterministic simulated outcomes.
   */
  resolveProduct(request: ProductResolveRequest): Promise<ProductResolveResult>

  listInvoices(): Promise<Invoice[]>
  getInvoice(invoiceId: string): Promise<Invoice | null>
  /** Always created as 'draft' — never touches stock. */
  createInvoice(input: NewInvoiceInput): Promise<Invoice>
  /** Marks paid and records one 'sale' stock movement per line item that has a catalogItemId. */
  markInvoicePaid(invoiceId: string, paymentMethod: InvoicePaymentMethod, paymentAmountCents: number): Promise<Invoice>
  /** Emails a rendered copy of the invoice (recipientEmail is typed at send time — see ScanWorkspacePage — not a persisted Customer record). Never fakes real delivery in demo mode. */
