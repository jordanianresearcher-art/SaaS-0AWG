// ---------------------------------------------------------------------------
// Universal product resolver — the one canonical, typed contract behind
// barcode lookup, typed search, and (later) photo lookup. See
// docs/PRODUCT_RESOLVER.md. lookupProductByUpc/lookupProductSuggestions
// above keep their existing narrower shapes for backward compatibility with
// already-shipped call sites (ScanWorkspacePage, ProductSuggestField) — both
// now delegate to resolveProduct() underneath rather than making their own
// separate external calls.
// ---------------------------------------------------------------------------

/** Where a resolved candidate's data actually came from — never conflated with "this shop's own catalog," which is checked locally before resolveProduct is ever called. */
export type ProductResolutionSource = 'resolution_cache' | 'verified_web_source' | 'ai_extracted'

/** Whether a reference price is MSRP, a verified retail price, or unclear — distinct from a shop's own selling price/cost, which a candidate never carries (see CatalogItem.defaultPriceCents/costCents for that). */
export type ProductPriceKind = 'msrp' | 'retail' | 'unknown'

export type ProductConfidenceLevel = 'high' | 'probable' | 'low'

/**
 * One ranked candidate identity for a scanned barcode or typed query that
 * didn't match anything already in this shop's catalog. Always a
 * *suggestion* — nothing here is written to the shop's catalog or cart
 * until staff explicitly act on it (see ScanWorkspacePage's confirmation
 * UI). referencePriceCents is a reference/market price, never a shop's own
 * confirmed selling price — the two are never overwritten by each other.
 */
export interface ProductResolutionCandidate {
  id: string
  source: ProductResolutionSource
  brand: string | null
  model: string | null
  name: string
  /** Free-text category hint (e.g. "car subwoofer") — not a raw ProductCategory value; map it with the existing guessCategoryFromName heuristic rather than trusting an AI-invented enum value. */
  categoryHint: string | null
  upc: string | null
  imageUrl: string | null
  referencePriceCents: number | null
  priceKind: ProductPriceKind
  priceSourceUrl: string | null
  priceSourceName: string | null
  /** 0-1 self-reported confidence, already discounted server-side for things like an unconfirmed barcode match. */
  confidence: number
  confidenceLevel: ProductConfidenceLevel
  /** Short human-readable reasons supporting this match. */
  evidence: string[]
  /** Things staff should double-check before trusting this candidate (e.g. "barcode not directly confirmed"). */
  warnings: string[]
}

/**
 * All three kinds prefer OpenAI (if OPENAI_API_KEY is set) and fall back
 * to Claude (if ANTHROPIC_API_KEY is set instead) — see resolve-product/
 * index.ts's resolveViaAi/resolveViaVision. 'photo' ports its *method*
 * (image + web_search + structured output, one call) from
 * car-audio-inventory's (this app's sister app) production vision route,
 * which is Claude-only there; this app runs the same combination through
 * OpenAI's Responses API too now, since that's not documented as
 * unsupported and OpenAI is the funded provider. Same graceful
 * degradation for all three either way — no funded key for the relevant
 * provider just means no candidates, never an error.
 */
export type ProductResolveRequest =
  /**
   * `brandHint` is the shop's current "brand lock" (see
   * src/lib/productSearch.ts) — the single biggest lever on result quality
   * for a manufacturer whose barcodes were never published anywhere. A bare
   * unpublished code can never match anything online; "Nemesis Audio
   * NA-12F" usually finds the manufacturer's own product page.
   *
   * `fast` skips the AI/web step and answers from the cache + UPCitemdb
   * only (~1s instead of 15-30s). The scan flow uses it so an unknown code
   * fails fast and staff can start typing what the box is, rather than
   * waiting out a search that was never going to resolve it. An empty fast
   * result is never cached, so a later full lookup still does the real work.
   */
  | { kind: 'barcode'; code: string; brandHint?: string | null; fast?: boolean }
  | { kind: 'text'; query: string; brandHint?: string | null }
  | { kind: 'photo'; imageBase64: string; mediaType: 'image/jpeg' | 'image/png' | 'image/webp' }

export interface ProductResolveResult {
  candidates: ProductResolutionCandidate[]
  /** The original code/query, always returned — even an empty-candidates result never loses what was scanned/typed, so the caller can fall back to a custom item with it prefilled. */
  retainedInput: string
  /**
   * False when the backend has no AI provider key funded, so nothing actually
   * looked the product up. Without this an unconfigured install is
   * indistinguishable from a genuine miss — both come back with zero
   * candidates — and a shop concludes lookup is broken. Demo mode reports
   * true: its results are canned, not absent.
   */
  aiConfigured: boolean
  /**
   * Set when a provider key IS funded but the call to it failed — a wrong
   * model name, an account out of credit, a revoked key, a network timeout.
   * Carries a short, safe summary ("OpenAI returned 404 (model_not_found)"),
   * never the provider's raw body, which can quote the request back.
   *
   * `aiConfigured` alone was not enough: with a key set, a broken provider and
   * a genuine miss both come back with zero candidates and `aiConfigured:
   * true`, so a shop whose key is present but not working is told to look for
   * a better photo forever. Null on a healthy lookup and on cached hits, where
   * no provider was asked anything.
   */
  aiError: string | null
  /**
   * True when the scanned code is one no public database can ever hold — a
   * store-assigned GS1 prefix, an internal item number, a bare part number —
   * so nothing was queried and nothing could have been found.
   *
   * Distinct from an ordinary empty result, and the distinction is the whole
   * point: "we searched everywhere and found nothing" sends staff hunting for
   * a better scan, while "there is nothing to search" sends them to the one
   * action that works — type the model, which binds the code to it for good.
   * See src/lib/barcodeIdentity.ts.
   */
  unresolvableBarcode: boolean
}

/**
 * Typing a model number is the primary intake path, and it used to fail
 * completely silently: the dropdown just said "No matches found" whether the
 * search genuinely came up empty, no AI key was funded, or the provider
 * rejected the call. Carrying the same two diagnostic fields the photo path
 * already had means the typed path can say which of the three happened.
 */
export interface ProductSuggestionResult {
  suggestions: ProductSuggestion[]
  aiConfigured: boolean
  aiError: string | null
}

/**
 * What a product-lookup self-test found out about this deployment.
 *
 * Every way lookup can be broken — no key, a key with no access to the
 * configured model, an unavailable tool identifier, a function that was never
 * deployed — produces the same empty candidate list from the outside. This
 * turns that into an answer someone can read and act on without opening Edge
 * Function logs.
 */
export interface ProductLookupSelfTest {
  ok: boolean
  /**
   * True/false when the backend actually told us, **null when we could not
   * find out** — the call never got far enough to ask.
   *
   * Null is the important state and it used to be missing. Every transport
   * failure reported `false`, so a request that never reached the function at
   * all rendered as "no AI provider key is set" — sending an owner who had
   * just set a key off to set it again. A diagnostic that guesses is worse
   * than no diagnostic.
   */
  aiConfigured: boolean | null
  provider: 'openai' | 'anthropic' | null
  /** The model actually used, after any override or auto-discovery. */
  model: string | null
  /** Which fallback level produced the answer — 1 is the richest. */
  rung: number | null
  rungLabel: string | null
  candidateCount: number
  /** The name of the first product found, as proof it really worked. */
  sample: string | null
  elapsedMs: number | null
  aiError: string | null
  /**
   * True when the answer came from the resolution cache rather than a live
   * provider call. A cache hit still proves the pipeline worked at some point,
   * but it says nothing about whether the key works *now* — so it is reported
   * rather than counted as a clean pass.
   */
  cached: boolean
  /** The deployed function's contract version, when it is new enough to report one. */
  functionVersion: number | null
}

